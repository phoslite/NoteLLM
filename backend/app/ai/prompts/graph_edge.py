"""跨书关联 LLM 打分与方向/原因增强提示词（M8 待办落地）。

输入两本书的书名与关键词，输出：
- strength：0~100 的关联强度（LLM 视角，可与关键词共现/笔记加权合并）；
- from_book：理论源头（A 或 B，null 表示无方向）；
- direction：承接 / 发展 / 批判（有方向时），无方向为「无」；
- relation_type：理论传承 / 概念共现 / 主题相似 / 应用扩展；
- reasons：3~6 条具体关联原因（基于书名与关键词）。
"""
SYSTEM_PROMPT = (
    "你是一位知识谱系与科学史专家。给定两本书及其关键词，判断它们之间的知识关联：\n"
    "1) strength：0~100 的关联强度（0=无关，100=同一理论体系的直接传承）；\n"
    "2) from_book：若存在理论传承方向（一本书是另一本的理论源头/被承接对象），返回源头书"
    "（\"A\" 或 \"B\"）；若只是主题相近/概念共现而无传承关系，返回 null；\n"
    "3) direction：有方向时用 承接（后者继承前者思想）/ 发展（后者在继承基础上推进发展）/ "
    "批判（后者对前者提出修正或批判），无方向时用 无；\n"
    "4) relation_type：理论传承（有明确师承/继承发展）/ 概念共现（共享术语概念）/ "
    "主题相似（同一主题领域）/ 应用扩展（把前者的方法应用到新场景）；\n"
    "5) reasons：3~6 条具体、可核实的关联原因，结合给定的书名与关键词，不要泛泛而谈。\n"    "6) reasons 中的数学符号必须使用 LaTeX（反斜杠在 JSON 中写成双反斜杠），禁止 Unicode 数学字符（如 Λ、∈、ℝ）。\n"
    "必须严格输出一个 JSON 对象，不要输出任何其他内容或代码围栏。JSON 结构：\n"
    '{"strength": 0~100, "from_book": "A"|"B"|null, "direction": "承接"|"发展"|"批判"|"无", '
    '"relation_type": "理论传承"|"概念共现"|"主题相似"|"应用扩展", "reasons": ["原因1", "原因2", ...]}'
)


def build_edge_user_prompt(book_a_title: str, book_b_title: str, keywords: list[str]) -> str:
    """构造跨书关联打分输入：两本书名 + 合并关键词预览。"""
    kw_line = "、".join(keywords) if keywords else "（两书关键词重叠不足，请依据书名与领域常识判断）"
    return (
        f"书 A：《{book_a_title}》\n"
        f"书 B：《{book_b_title}》\n"
        f"两书合并关键词（按权重降序）：{kw_line}\n\n"
        "请评估关联强度与方向，输出 JSON。"
    )